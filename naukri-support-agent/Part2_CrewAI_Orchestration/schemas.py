"""
Task 9: Pydantic Structured Output Schema.

This file defines the exact format that every response from our
AI agents must follow, ensuring consistency and preventing runtime errors.
"""

from typing import Optional
import json
from pathlib import Path
from pydantic import BaseModel, Field, ValidationError


# ----------------------------------------------------------------------
# 1. The Standard Response Form (Schema)
# ----------------------------------------------------------------------
class AgentResponse(BaseModel):
    """
    Every response generated by our CrewAI agents must match this exact format.
    """
    query: str                                                      # What the user asked
    answer: str                                                     # The agent's final synthesized answer
    source_documents: list[str] = Field(default_factory=list)       # List of source policy docs (e.g. ['kb_005'])
    confidence_score: float = Field(ge=0.0, le=1.0)                 # Must be between 0.0 and 1.0
    is_grounded: bool                                               # True if answer is from docs, False if out-of-scope
    escalation_score: Optional[float] = None                        # Only used for job application lookups
    guardrail_flags: dict = Field(default_factory=dict)             # Security flags (PII, injection, etc.)


# ----------------------------------------------------------------------
# 2. Validation Helper Function
# ----------------------------------------------------------------------
def validate_agent_response(payload: dict | str | AgentResponse) -> AgentResponse:
    """
    Validates a dictionary, raw JSON string, or existing instance against AgentResponse.
    Raises ValidationError if any field is missing or invalid.
    """
    if isinstance(payload, AgentResponse):
        return payload
    if isinstance(payload, str):
        payload = json.loads(payload)
    return AgentResponse(**payload)


# ----------------------------------------------------------------------
# 3. Simple Test to Prove It Works
# ----------------------------------------------------------------------
if __name__ == "__main__":
    print("Testing AgentResponse schema with best practice defaults...\n")

    # Example 1: A normal HR Policy Answer
    policy_response = {
        "query": "What is the notice period policy?",
        "answer": "Employees must serve a 60-day notice period upon resignation.",
        "source_documents": ["kb_005"],
        "confidence_score": 0.74,
        "is_grounded": True,
    }
    checked_policy = validate_agent_response(policy_response)
    print("Test 1 (Policy Response) Passed:")
    print(checked_policy.model_dump())
    print("-" * 50)

    # Example 2: An Application Status Lookup with Escalation Score
    lookup_response = {
        "query": "Check status of APP-045",
        "answer": "Application APP-045 is in Screening. Escalation recommended.",
        "source_documents": ["dataset.py:APP-045"],
        "confidence_score": 1.0,
        "is_grounded": True,
        "escalation_score": 0.96,
    }
    checked_lookup = validate_agent_response(lookup_response)
    print("Test 2 (Application Lookup) Passed:")
    print(checked_lookup.model_dump())
    print("-" * 50)

    # Example 3: Deliberately Bad Data (Score > 1.0) - Pydantic should catch it!
    bad_data = {
        "query": "What is the notice period?",
        "answer": "60 days",
        "confidence_score": 2.5,  # Invalid! Max is 1.0
        "is_grounded": True,
    }
    try:
        validate_agent_response(bad_data)
        print("Test 3 Failed: Invalid score was not caught!")
    except ValidationError:
        print("Test 3 (Catching Invalid Data) Passed:")
        print("Pydantic successfully blocked confidence_score = 2.5 (must be <= 1.0).")
    print("-" * 50)

    # Save verification result to transcript
    transcript_path = Path(__file__).resolve().parent.parent / "transcripts" / "part2_schemas_verification.txt"
    with open(transcript_path, "w", encoding="utf-8") as f:
        f.write("PART 2 TASK 9: STRUCTURED OUTPUT SCHEMA VERIFICATION\n")
        f.write("AgentResponse schema verified successfully with best-practice default factories.\n")
        f.write(f"- Test 1 Policy: {checked_policy.model_dump()}\n")
        f.write(f"- Test 2 Lookup: {checked_lookup.model_dump()}\n")
        f.write("- Test 3 Error Check: Successfully blocked invalid confidence_score 2.5\n")
    print(f"\nSaved verification to: {transcript_path}")
